import java.util.Properties

plugins {
    id("com.android.application")
    id("org.jetbrains.kotlin.android")
    id("org.jetbrains.kotlin.plugin.compose")
}

// Llave de firma propia (keystore.properties en la raíz). Si no existe, se firma con la llave de debug.
val firma = Properties().apply {
    val f = rootProject.file("keystore.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}

android {
    namespace = "com.misfinanzas.app"
    compileSdk = 35

    defaultConfig {
        applicationId = "com.misfinanzas.app"
        minSdk = 26
        targetSdk = 35
        versionCode = 3
        versionName = "1.2"
        // Repositorio de GitHub donde se publican las versiones (releases con el APK).
        buildConfigField("String", "REPO", "\"Chxxtxs/MisFinanzas\"")
    }

    signingConfigs {
        if (!firma.isEmpty) {
            create("propia") {
                storeFile = rootProject.file(firma.getProperty("storeFile"))
                storePassword = firma.getProperty("storePassword")
                keyAlias = firma.getProperty("keyAlias")
                keyPassword = firma.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            signingConfig = signingConfigs.findByName("propia") ?: signingConfigs.getByName("debug")
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    kotlinOptions {
        jvmTarget = "17"
    }
    buildFeatures {
        compose = true
        buildConfig = true
    }
}

